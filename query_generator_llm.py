"""Optional LLM integration for QueryCraft AI.

Supports OpenAI-compatible endpoints or Google Gemini API if environment
variables (OPENAI_API_KEY or GEMINI_API_KEY) are configured.
Strictly validates any LLM-produced SQL against the database security filter
before returning.
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from typing import Optional

from database import sanitize_and_validate_sql
from query_generator import GeneratedQuery

SYSTEM_PROMPT = """You are an expert SQLite SQL query generator for the Chinook Music Store database.
The database schema consists of:
- Artist (ArtistId, Name)
- Album (AlbumId, Title, ArtistId)
- Track (TrackId, Name, AlbumId, MediaTypeId, GenreId, Composer, Milliseconds, Bytes, UnitPrice)
- Genre (GenreId, Name)
- MediaType (MediaTypeId, Name)
- Invoice (InvoiceId, CustomerId, InvoiceDate, BillingAddress, BillingCity, BillingState, BillingCountry, BillingPostalCode, Total)
- InvoiceLine (InvoiceLineId, InvoiceId, TrackId, UnitPrice, Quantity)
- Customer (CustomerId, FirstName, LastName, Company, Address, City, State, Country, PostalCode, Phone, Fax, Email, SupportRepId)
- Employee (EmployeeId, LastName, FirstName, Title, ReportsTo, BirthDate, HireDate, Address, City, State, Country, PostalCode, Phone, Fax, Email)
- Playlist (PlaylistId, Name)
- PlaylistTrack (PlaylistId, TrackId)

Rules:
1. Generate ONLY a single safe read-only SELECT or WITH (CTE) query.
2. NEVER generate INSERT, UPDATE, DELETE, DROP, ALTER, PRAGMA, ATTACH, or multi-statement queries.
3. For duration questions, 1 minute = 60000 milliseconds.
4. Avoid double-counting invoice revenue: for line-item revenue use SUM(UnitPrice * Quantity) from InvoiceLine.
5. Respond with ONLY valid JSON in this exact structure:
{
  "sql": "SELECT ...;",
  "explanation": "Short 1-2 sentence plain-English explanation."
}
"""


def generate_query_with_llm(question: str) -> Optional[GeneratedQuery]:
    """Generates SQL using an available LLM API (OpenAI or Gemini).

    Returns None if no API keys are present or if the API call fails.
    """
    openai_key = os.getenv("OPENAI_API_KEY", "").strip()
    gemini_key = os.getenv("GEMINI_API_KEY", "").strip()

    if not openai_key and not gemini_key:
        return None

    # Try OpenAI first if key is present
    if openai_key:
        try:
            url = os.getenv("OPENAI_BASE_URL", "https://api.openai.com/v1/chat/completions")
            headers = {
                "Content-Type": "application/json",
                "Authorization": f"Bearer {openai_key}",
            }
            body = {
                "model": os.getenv("OPENAI_MODEL", "gpt-4o-mini"),
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": question},
                ],
                "response_format": {"type": "json_object"},
                "temperature": 0.0,
            }
            req = urllib.request.Request(url, data=json.dumps(body).encode("utf-8"), headers=headers, method="POST")
            with urllib.request.urlopen(req, timeout=10.0) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                content = data["choices"][0]["message"]["content"]
                parsed = json.loads(content)
                sql = parsed.get("sql", "").strip()
                explanation = parsed.get("explanation", "").strip()

                # Strictly validate generated SQL
                sanitized_sql = sanitize_and_validate_sql(sql)
                return GeneratedQuery(
                    user_question=question,
                    sql=sanitized_sql,
                    display_sql=sanitized_sql,
                    explanation=explanation or "Query generated by external LLM.",
                    is_supported=True,
                    confidence=0.95,
                    engine_used=f"External LLM ({body['model']})",
                )
        except Exception:
            # Fall back cleanly
            pass

    # Try Gemini if key is present
    if gemini_key:
        try:
            model = os.getenv("GEMINI_MODEL", "gemini-1.5-flash")
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={gemini_key}"
            headers = {"Content-Type": "application/json"}
            body = {
                "contents": [
                    {"parts": [{"text": f"{SYSTEM_PROMPT}\n\nUser Question: {question}"}]}
                ],
                "generationConfig": {
                    "responseMimeType": "application/json",
                    "temperature": 0.0,
                }
            }
            req = urllib.request.Request(url, data=json.dumps(body).encode("utf-8"), headers=headers, method="POST")
            with urllib.request.urlopen(req, timeout=10.0) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                text = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(text)
                sql = parsed.get("sql", "").strip()
                explanation = parsed.get("explanation", "").strip()

                sanitized_sql = sanitize_and_validate_sql(sql)
                return GeneratedQuery(
                    user_question=question,
                    sql=sanitized_sql,
                    display_sql=sanitized_sql,
                    explanation=explanation or "Query generated by Gemini LLM.",
                    is_supported=True,
                    confidence=0.95,
                    engine_used=f"External LLM ({model})",
                )
        except Exception:
            pass

    return None
